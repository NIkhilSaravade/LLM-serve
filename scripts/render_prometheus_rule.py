"""Render deploy/k8s/monitoring/prometheus-rule.yaml from deploy/prometheus/alerts.yml.

One source of truth for alerts: compose loads alerts.yml directly, Kubernetes gets a
PrometheusRule generated from it. CI runs this and fails if the committed file differs.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "deploy" / "prometheus" / "alerts.yml"
DST = ROOT / "deploy" / "k8s" / "monitoring" / "prometheus-rule.yaml"


def render() -> str:
    groups = yaml.safe_load(SRC.read_text(encoding="utf-8"))["groups"]
    doc = {"apiVersion": "monitoring.coreos.com/v1", "kind": "PrometheusRule",
           "metadata": {"name": "llm-serve", "labels": {"app": "llm-serve"}},
           "spec": {"groups": groups}}
    header = ("# GENERATED by scripts/render_prometheus_rule.py from deploy/prometheus/alerts.yml.\n"
              "# Do not edit by hand.\n")
    return header + yaml.safe_dump(doc, sort_keys=False, width=100)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text(encoding="utf-8") != text:
            sys.exit(f"{DST} is stale: run python scripts/render_prometheus_rule.py")
        print("prometheus rule is up to date")
    else:
        DST.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", DST)
